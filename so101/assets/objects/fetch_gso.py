"""Download the Google Scanned Objects subset listed in gso_index.json and write one
MuJoCo object file per object.

Source: github.com/kevinzakka/mujoco_scanned_objects (pinned commit below).
Licence: meshes/textures CC-BY 4.0 (Google Scanned Objects, Downs et al. 2022);
original MJCF MIT. The object.xml files written here are generated by this script.

Usage (from anywhere; needs only the standard library):
    python so101/assets/objects/fetch_gso.py            # download missing files + (re)write object.xml
    python so101/assets/objects/fetch_gso.py --xml-only # just rewrite object.xml from gso_index.json

Each object ends up in gso/<name>/:
    model.obj                visual mesh (textured, group 2, no collisions)
    model_collision_N.obj    convex V-HACD hulls used for collision (group 3)
    texture.png
    object.xml               self-contained MJCF: body "object" with a freejoint

Add objects to a scene with MuJoCo's model attach (paths resolve relative to object.xml,
and the prefix namespaces every name, so several objects - or several copies of the
same object - can coexist):

    <asset>
      <model name="bottle" file="objects/gso/CoQ10/object.xml"/>
    </asset>
    <worldbody>
      <frame pos="0.2 0 0.001">
        <attach model="bottle" body="object" prefix="obj0_"/>
      </frame>
    </worldbody>
"""

import argparse
import json
import os
import sys
import urllib.request
from concurrent.futures import ThreadPoolExecutor

REPO = "kevinzakka/mujoco_scanned_objects"
COMMIT = "6ff8d275cebfd5b47e49685e3cfbe64b20e49a3c"
RAW = f"https://raw.githubusercontent.com/{REPO}/{COMMIT}/models"

HERE = os.path.dirname(os.path.abspath(__file__))
INDEX = os.path.join(HERE, "gso_index.json")

FRICTION = "1.0 0.005 0.0001"  # slide, torsion, roll (condim 6 uses all three)


def object_xml(e):
    n = e["collision_geoms"]
    meshes = "\n".join(
        f'    <mesh name="collision_{i}" file="model_collision_{i}.obj"/>' for i in range(n)
    )
    geoms = "\n".join(
        f'      <geom class="collision" mesh="collision_{i}"/>' for i in range(n)
    )
    com = " ".join(f"{x:g}" for x in e["com_m"])
    fi = " ".join(f"{x:.4g}" for x in e["fullinertia"])
    return f"""<!-- Google Scanned Objects: {e['src']}
     "{e['phrase']}"  dims (m) {e['dims_m']}  min width {e['min_width_m']} m  mass {e['mass_kg']} kg
     Meshes/texture CC-BY 4.0 (Google). Generated by fetch_gso.py; attach it, don't include it:
       <model name="x" file=".../object.xml"/> + <attach model="x" body="object" prefix="p_"/>
     Body origin = mesh origin: the object rests on z=0 of its body frame. -->
<mujoco model="{e['name']}">
  <default>
    <default class="visual">
      <geom type="mesh" contype="0" conaffinity="0" group="2"/>
    </default>
    <default class="collision">
      <geom type="mesh" group="3" condim="6" friction="{FRICTION}"/>
    </default>
  </default>
  <asset>
    <texture type="2d" name="texture" file="texture.png"/>
    <material name="material" texture="texture" specular="0.5" shininess="0.5"/>
    <mesh name="visual" file="model.obj"/>
{meshes}
  </asset>
  <worldbody>
    <body name="object">
      <freejoint name="freejoint"/>
      <inertial pos="{com}" mass="{e['mass_kg']}" fullinertia="{fi}"/>
      <geom name="visual" class="visual" mesh="visual" material="material"/>
{geoms}
    </body>
  </worldbody>
</mujoco>
"""


def fetch(url, dst):
    if os.path.exists(dst) and os.path.getsize(dst) > 0:
        return 0
    tmp = dst + ".part"
    with urllib.request.urlopen(url, timeout=60) as r, open(tmp, "wb") as f:
        f.write(r.read())
    os.replace(tmp, dst)
    return os.path.getsize(dst)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--xml-only", action="store_true")
    ap.add_argument("--workers", type=int, default=8)
    args = ap.parse_args()

    index = json.load(open(INDEX, encoding="utf-8"))
    jobs = []
    for e in index:
        d = os.path.join(HERE, e["dir"])
        os.makedirs(d, exist_ok=True)
        src = urllib.request.quote(e["src"])  # some upstream names are non-ASCII
        files = ["model.obj", "texture.png"] + [
            f"model_collision_{i}.obj" for i in range(e["collision_geoms"])
        ]
        if not args.xml_only:
            jobs += [(f"{RAW}/{src}/{f}", os.path.join(d, f)) for f in files]

    if jobs:
        with ThreadPoolExecutor(args.workers) as ex:
            got = sum(ex.map(lambda j: fetch(*j), jobs))
        print(f"downloaded {got / 1e6:.1f} MB ({len(jobs)} files checked)")

    for e in index:
        with open(os.path.join(HERE, e["xml"]), "w", encoding="utf-8", newline="\n") as f:
            f.write(object_xml(e))
    print(f"wrote {len(index)} object.xml files under {os.path.join(HERE, 'gso')}")


if __name__ == "__main__":
    sys.exit(main())
