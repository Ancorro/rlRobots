"""Rebuild so101/assets/unitree_g1/ (the Menagerie G1 + Dex3 model that fetch_g1.py normally clones from GitHub) when
GitHub is unreachable but PyPI is.

The committed scene_g1_cull.xml was generated by `so101.g1_warp make-scene` from scene_g1.xml + the Menagerie model.
At level "cull" the only change to the robot is that collision geoms on bodies the welded robot cannot use were turned
off (contype="0" conaffinity="0" added); everything else (bodies, inertials, joints, actuators, sensors, keyframe,
defaults) is the Menagerie model verbatim as MjSpec.to_xml writes it. This script undoes the culling and writes the
robot part to unitree_g1/g1_with_hands.xml, and takes the STL meshes (Unitree's g1_description, BSD-3, the same files
Menagerie vendors) from a PyPI wheel: example-robot-data (default) or holosoma.

    python so101/assets/rebuild_g1.py [--meshes=DIR]
"""
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

HERE = Path(__file__).parent
DEST = HERE / "unitree_g1"
CULL = HERE / "scene_g1_cull.xml"
HEAD = """<!-- Rebuilt by so101/assets/rebuild_g1.py from scene_g1_cull.xml (MuJoCo Menagerie unitree_g1/g1_with_hands.xml,
     commit c96a32d, BSD-3-Clause: see ../LICENSE-unitree_g1). Meshes: Unitree g1_description (BSD-3). -->
"""


def robot_xml(text):
    """The robot part of the culled scene: everything but scene_g1.xml's own additions, with the culling undone."""
    # the scene's additions (see scene_g1.xml): size, visual, groundplane texture/material, object default, the
    # table/ground/trays/shelf/cameras/lights, the "object" class
    text = text.split("\n", 1)[1]  # the generated-by comment
    text = re.sub(r"\s*<size memory=\"64M\"/>", "", text)
    text = re.sub(r"\s*<visual>.*?</visual>", "", text, flags=re.S)
    text = re.sub(r"\s*<texture[^>]*groundplane[^>]*/>", "", text)
    text = re.sub(r"\s*<material name=\"(groundplane|ground)\"[^>]*/>", "", text)
    text = re.sub(r"\s*<default class=\"object\">.*?</default>", "", text, flags=re.S)
    text = re.sub(r"\s*<geom name=\"(floor|ground)\"[^>]*/>", "", text)
    text = re.sub(r"\s*<camera [^>]*/>", "", text)
    text = re.sub(r"\s*<light [^>]*/>", "", text)
    text = re.sub(r"\s*<body name=\"(red_tray|blue_tray|shelf)\"[^>]*>.*?</body>", "", text, flags=re.S)
    text = re.sub(r"\s*<body name=\"workspace_center\"[^>]*/>", "", text)
    # undo the culling: collision/foot-class geoms had their contacts turned off
    text, n = re.subn(r'(<geom class="(collision|foot)"[^>]*?) contype="0" conaffinity="0"', r"\1", text)
    assert n > 0, "nothing to un-cull?"
    text = text.replace('<mujoco model="g1_general">', '<mujoco model="g1_29dof_with_hand_rev_1_0">')
    text = text.replace('meshdir="unitree_g1/assets/"', 'meshdir="assets"')
    left = [l for l in text.splitlines() if 'contype="0" conaffinity="0"' in l]
    assert len(left) == 1 and 'class="visual"' in text and "group=\"2\"" in left[0], f"unexpected leftover culling: {left}"
    return HEAD + text


def mesh_dir(arg):
    if arg:
        return Path(arg)
    # a local wheel cache, or download one from PyPI (no deps; example-robot-data is ~130 MB, holosoma ~45 MB)
    tmp = Path(tempfile.mkdtemp())
    for pkg, sub in (("example-robot-data", "cmeel.prefix/share/example-robot-data/robots/g1_description/meshes"),
                     ("holosoma", "holosoma/data/robots/g1/meshes")):
        try:
            subprocess.run([sys.executable, "-m", "pip", "download", "-q", "--no-deps", "-d", str(tmp), pkg], check=True)
        except subprocess.CalledProcessError:
            continue
        whl = next(tmp.glob("*.whl"))
        with zipfile.ZipFile(whl) as z:
            for name in z.namelist():
                if name.startswith(sub) and name.endswith(".STL"):
                    z.extract(name, tmp)
        return tmp / sub
    raise SystemExit("could not download the G1 meshes from PyPI")


def main():
    arg = next((a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith("--meshes=")), None)
    xml = robot_xml(CULL.read_text())
    DEST.mkdir(exist_ok=True)
    (DEST / "g1_with_hands.xml").write_text(xml)
    src = mesh_dir(arg)
    assets = DEST / "assets"
    assets.mkdir(exist_ok=True)
    need = sorted(set(re.findall(r'file="([^"]+\.STL)"', xml)))
    missing = [f for f in need if not (src / f).exists()]
    assert not missing, f"meshes missing from {src}: {missing}"
    for f in need:
        shutil.copy(src / f, assets / f)
    shutil.copy(HERE / "LICENSE-unitree_g1", DEST / "LICENSE")
    print(f"wrote {DEST / 'g1_with_hands.xml'} and {len(need)} meshes from {src}")


if __name__ == "__main__":
    main()
